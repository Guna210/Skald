"""Generate golden text-pipeline expectations and the human review report.

Records chapter-level metrics for the two public-domain EPUB fixtures into
``core/tests/golden/text_golden.json`` and writes ``docs/verification/text-review.md``
for human skimming.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from skald_core.book import load_epub_book
from skald_core.schemas.models import Book
from skald_core.text import apply_lexicon, chunk_paragraph, normalize

REPO_ROOT = Path(__file__).resolve().parents[3]
PUBLIC_DOMAIN_DIR = REPO_ROOT / "core" / "tests" / "data" / "public_domain"
GOLDEN_PATH = Path(__file__).resolve().parent / "text_golden.json"
REVIEW_PATH = REPO_ROOT / "docs" / "verification" / "text-review.md"

PUBLIC_DOMAIN_EPUBS: tuple[str, ...] = (
    "pg43-jekyll-hyde.epub",
    "pg46-christmas-carol.epub",
)
MAX_CHARS = 400


def extract_book_golden(
    epub_path: Path, *, max_chars: int = MAX_CHARS
) -> tuple[Book, dict[str, Any]]:
    """Run import + normalize + empty-lexicon + chunking on ``epub_path``."""
    book = load_epub_book(epub_path)
    chapters_data: list[dict[str, Any]] = []

    for ch in book.chapters:
        display_char_count = sum(len(p.text) for p in ch.paragraphs)
        chunk_count = 0
        for p in ch.paragraphs:
            synth_text, _ = apply_lexicon(normalize(p.text), [])
            res = chunk_paragraph(ch.id, p.id, synth_text, book.language, max_chars=max_chars)
            chunk_count += len(res.chunks)
        chapters_data.append(
            {
                "chunk_count": chunk_count,
                "display_char_count": display_char_count,
                "paragraph_count": len(ch.paragraphs),
                "title": ch.title,
            }
        )

    book_data: dict[str, Any] = {
        "authors": list(book.authors),
        "chapters": chapters_data,
        "language": book.language,
        "title": book.title,
    }
    return book, book_data


def _md_blockquote(text: str) -> str:
    lines = text.split("\n")
    if len(lines) == 1:
        return f"> {lines[0]}"
    return "\n".join(
        f"> {line}  " if idx < len(lines) - 1 else f"> {line}" for idx, line in enumerate(lines)
    )


def render_text_review(books: list[tuple[str, Book]]) -> str:
    """Render ``docs/verification/text-review.md`` from extracted public-domain books."""
    lines: list[str] = [
        "# Public-Domain EPUB Text Extraction Review",
        "",
        (
            "Generated by `core/tests/golden/make_golden_text.py` from the two public-domain "
            "EPUB fixtures so you can check extraction quality in about 10 minutes."
        ),
        "",
        "## What to look for",
        "",
        "- **Wrong chapter breaks:** chapters split in the middle of a story, merged together, "
        "or titled with body text instead of a chapter heading.",
        "- **Missing or duplicated text:** missing opening or closing lines, cut-off sentences, "
        "or text repeated across chapter boundaries.",
        "- **Page numbers or notes read aloud:** stray page numbers, running headers/footers, "
        "footnote markers, or footnote/endnote bodies appearing in the story.",
        "- **Odd characters:** garbled symbols, broken quotes or apostrophes, leftover HTML "
        "markup, or unusual spacing and line breaks.",
        "",
        "## Known issues (already noted — no need to report)",
        "",
        "- **Gutenberg header, credits, and licence chapters:** Project Gutenberg includes "
        "front-matter and licence pages in the spine, so they appear as chapters (users can "
        "untick them in the Book screen).",
        "- **Untagged `Contents` and `ILLUSTRATIONS` tables:** These pages in the source EPUBs "
        "have no `toc` or `landmarks` tags, so Skald does not auto-skip them unless they fall "
        "under the 200-character `short` rule.",
        "- ***A Christmas Carol*'s `div.fig` captions mid-stave:** Illustration captions in this "
        'EPUB use non-standard `<div class="fig">` elements rather than `<figcaption>`, so they '
        "stay in the extracted text; some are also TOC anchor targets, which splits a stave at "
        "the illustration and places the caption at the boundary.",
        "- **Empty cover wrapper pages:** Cover-only XHTML pages extract 0 paragraphs and are "
        "marked `suggested-skip (short)`.",
        "",
    ]

    for book_num, (filename, book) in enumerate(books, start=1):
        included_count = sum(1 for ch in book.chapters if ch.included)
        skip_count = len(book.chapters) - included_count
        authors = ", ".join(book.authors) if book.authors else "(none)"
        lines.extend(
            [
                f"## {book_num}. {book.title} (`{filename}`)",
                "",
                (
                    f"- **Author(s):** {authors} · **Language:** `{book.language or 'unset'}` · "
                    f"**Chapters:** {len(book.chapters)} total "
                    f"({included_count} included, {skip_count} suggested-skip)"
                ),
                "",
            ]
        )

        for ch_num, ch in enumerate(book.chapters, start=1):
            if ch.included:
                status = "included"
            else:
                reasons = list(ch.skip_reasons)
                if not ch.linear:
                    reasons.append("non-linear")
                reason_str = ", ".join(reasons) if reasons else "skipped"
                status = f"suggested-skip ({reason_str})"

            lines.extend(
                [
                    f"### {ch_num}. {ch.title}",
                    "",
                    f"- **Status:** {status} · **Paragraphs:** {len(ch.paragraphs)}",
                ]
            )
            if not ch.paragraphs:
                lines.append("- **Text:** *(none — 0 paragraphs extracted)*")
            elif len(ch.paragraphs) == 1:
                lines.append("- **First & last paragraph (single paragraph):**")
                lines.append(_md_blockquote(ch.paragraphs[0].text))
            else:
                lines.append("- **First paragraph:**")
                lines.append(_md_blockquote(ch.paragraphs[0].text))
                lines.append("- **Last paragraph:**")
                lines.append(_md_blockquote(ch.paragraphs[-1].text))
            lines.append("")

    return "\n".join(lines).rstrip("\n") + "\n"


def generate(
    *,
    golden_path: Path | None = None,
    review_path: Path | None = None,
    public_domain_dir: Path = PUBLIC_DOMAIN_DIR,
    force: bool = False,
) -> tuple[Path, Path]:
    """Generate ``text_golden.json`` and ``text-review.md``."""
    resolved_golden = GOLDEN_PATH if golden_path is None else golden_path
    resolved_review = REVIEW_PATH if review_path is None else review_path
    if resolved_golden.exists() and not force:
        raise FileExistsError(
            f"Refusing to overwrite existing golden file {resolved_golden} without --force. "
            "Agents must never re-record golden values to make a test pass; "
            "re-recording requires Orchestrator approval (SPEC C3.3)."
        )

    books_payload: dict[str, Any] = {}
    review_books: list[tuple[str, Book]] = []
    for filename in PUBLIC_DOMAIN_EPUBS:
        epub_path = public_domain_dir / filename
        book, book_data = extract_book_golden(epub_path, max_chars=MAX_CHARS)
        books_payload[filename] = book_data
        review_books.append((filename, book))

    golden_payload: dict[str, Any] = {
        "books": books_payload,
        "max_chars": MAX_CHARS,
    }
    golden_json = json.dumps(golden_payload, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    review_md = render_text_review(review_books)

    resolved_golden.parent.mkdir(parents=True, exist_ok=True)
    with resolved_golden.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(golden_json)

    resolved_review.parent.mkdir(parents=True, exist_ok=True)
    with resolved_review.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(review_md)

    return resolved_golden, resolved_review


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(
            "Record golden text-pipeline metrics for the public-domain EPUB fixtures and "
            "generate docs/verification/text-review.md. "
            "Agents must NEVER re-record golden values to make a test pass; "
            "re-recording requires Orchestrator approval (SPEC C3.3)."
        )
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help=(
            "Overwrite an existing golden JSON file. Only use with Orchestrator approval "
            "(SPEC C3.3); agents must never re-record golden values to make a test pass."
        ),
    )
    args = parser.parse_args(argv)
    try:
        golden_path, review_path = generate(force=args.force)
    except FileExistsError as exc:
        print(f"Error: {exc}", file=sys.stderr)
        return 1
    print(f"wrote {golden_path}")
    print(f"wrote {review_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
